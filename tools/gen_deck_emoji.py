#!/usr/bin/env python3
"""Regenerate examples/companion_radio/ui-deck/DeckEmoji.h.

The T-Deck draws the phone app's reaction emoji (Reactions.ALL, in wire
order) as 16x16 RGB565 + alpha images taken from Noto Emoji's 32 px PNGs
(googlefonts/noto-emoji, 2D/png/32; Apache License 2.0).

    tools/gen_deck_emoji.py <Reactions.kt> <noto 2D/png/32 dir> <out .h>

Reactions.kt is the app's shared/.../protocol/Reactions.kt; the order of
its lists is the wire index and must match KISS_EMOJI in
examples/companion_radio/ui-kiss/KissText.h.
"""
import re
import sys
from PIL import Image

def main(reactions_kt, png_dir, out):
    src = open(reactions_kt, encoding="utf-8").read()
    emoji = []
    for name in ["QUICK", "SMILEYS", "GESTURES", "HEARTS", "OBJECTS"]:
        body = re.search(r"val %s: List<String> = listOf\((.*?)\n    \)" % name, src, re.S).group(1)
        emoji += re.findall(r'"([^"]+)"', body)
    files = ["emoji_u" + "_".join("%04x" % ord(c) for c in e if ord(c) != 0xFE0F) + ".png" for e in emoji]
    uniq = []
    for f in files:
        if f not in uniq:
            uniq.append(f)
    L = ["#pragma once\n",
         "// Colour emoji for the T-Deck: the phone app's reaction list (Reactions.ALL,",
         "// in wire order, as KISS_EMOJI in ../ui-kiss/KissText.h), 16x16 RGB565 plus",
         "// 8-bit alpha. Images: Noto Emoji (googlefonts/noto-emoji, 2D/png/32),",
         "// Copyright Google Inc., Apache License 2.0; scaled down from 32x32.",
         "// Generated by tools/gen_deck_emoji.py; regenerate rather than edit.\n",
         "#include <stdint.h>\n",
         "#define DECK_EMOJI_PX     16",
         "#define DECK_EMOJI_IMAGES %d\n" % len(uniq),
         "// KISS_EMOJI index -> image (a few emoji appear twice in the app's list)",
         "static const uint8_t DECK_EMOJI_IMAGE[%d] = {" % len(files)]
    idx = [uniq.index(f) for f in files]
    for i in range(0, len(idx), 24):
        L.append("  " + ", ".join(str(x) for x in idx[i:i + 24]) + ",")
    L.append("};\n")
    rgb, alpha = [], []
    for f in uniq:
        im = Image.open(png_dir + "/" + f).convert("RGBA").resize((16, 16), Image.LANCZOS)
        px = [im.getpixel((x, y)) for y in range(16) for x in range(16)]
        rgb.append([((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b, a in px])
        alpha.append([a for r, g, b, a in px])
    L.append("static const uint16_t DECK_EMOJI_RGB[DECK_EMOJI_IMAGES][DECK_EMOJI_PX * DECK_EMOJI_PX] = {")
    for k, v in enumerate(rgb):
        L.append("  { // %s" % uniq[k])
        for i in range(0, 256, 16):
            L.append("    " + ",".join("0x%04X" % x for x in v[i:i + 16]) + ",")
        L.append("  },")
    L.append("};\n")
    L.append("static const uint8_t DECK_EMOJI_ALPHA[DECK_EMOJI_IMAGES][DECK_EMOJI_PX * DECK_EMOJI_PX] = {")
    for v in alpha:
        L.append("  {")
        for i in range(0, 256, 32):
            L.append("    " + ",".join(str(x) for x in v[i:i + 32]) + ",")
        L.append("  },")
    L.append("};")
    open(out, "w").write("\n".join(L) + "\n")
    print("%d emoji, %d images -> %s" % (len(files), len(uniq), out))

if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
